package com.tinyquery.datasource.spec;

/**
 * 数据源的可用状态。
 *
 * <p>引入这个枚举是为了把三种「用不了」区分开 —— 它们的原因和处理方式完全不同，
 * 混成一个「失败」会让用户无从下手：</p>
 *
 * <ul>
 *   <li>{@link #OK} —— 已加载，可正常查询。</li>
 *   <li>{@link #NEEDS_PASSWORD} —— 配置在，但缺密码。当前版本不保存密码，
 *       所以这不是错误，而是预期内的正常状态：用户注册时没勾保存，
 *       或压根没有保存密码这回事。用户补上密码就能用。</li>
 *   <li>{@link #FAILED} —— 真正加载不了：CSV 文件被删了、数据库连不上、配置非法。
 *       用户需要去修配置或修环境。</li>
 * </ul>
 *
 * <p>区分 {@code NEEDS_PASSWORD} 与 {@code FAILED} 的现实意义：
 * 前者提示「请输入密码」，后者提示「加载失败 + 原因」。
 * 若混为一谈，用户会被要求为一个「只是没填密码」的数据源去排查文件路径。</p>
 */
public enum LoadStatus {

    /** 已加载，可用 */
    OK,

    /** 缺少密码等敏感必填项，等用户补上 */
    NEEDS_PASSWORD,

    /** 加载失败，附原因 */
    FAILED
}
